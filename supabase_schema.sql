-- Run in Supabase SQL Editor or with the Supabase CLI.
create table if not exists public.users (
  user_id bigint primary key,
  full_name text not null,
  username text,
  selected_type text check (selected_type in ('teacher','group')),
  selected_teacher text,
  selected_group text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.schedule_periods (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  month integer not null check (month between 1 and 12),
  status text not null check (status in ('draft','active','archived')),
  source_filename text,
  uploaded_by bigint,
  created_at timestamptz not null default now(),
  activated_at timestamptz
);
create unique index if not exists one_active_schedule_per_month
  on public.schedule_periods(year,month) where status='active';
create index if not exists schedule_period_lookup on public.schedule_periods(year,month,status);

create table if not exists public.schedules (
  id bigint generated by default as identity primary key,
  period_id bigint not null references public.schedule_periods(id) on delete cascade,
  teacher text not null,
  group_name text not null,
  day_of_week text not null,
  day_index integer not null check (day_index between 1 and 7),
  lesson_date date,
  pair_number integer check (pair_number between 1 and 12),
  time_range text not null,
  subject text not null,
  lesson_type text not null,
  room text not null,
  status text not null default 'scheduled' check (status in ('scheduled','cancelled'))
);
create index if not exists schedules_teacher_idx on public.schedules(teacher);
create index if not exists schedules_group_idx on public.schedules(group_name);
create index if not exists schedules_period_day_idx on public.schedules(period_id,day_index,pair_number);
create index if not exists schedules_lesson_date_idx on public.schedules(lesson_date) where lesson_date is not null;
create unique index if not exists schedules_no_duplicate_rows on public.schedules
  (period_id,teacher,group_name,day_index,coalesce(lesson_date,'0001-01-01'::date),coalesce(pair_number,0),time_range,subject,room);

create table if not exists public.schedule_imports (
  id bigint generated by default as identity primary key,
  file_name text not null,
  admin_id bigint not null,
  import_type text not null check (import_type in ('weekly','monthly')),
  year integer not null check (year between 2000 and 2100),
  month integer not null check (month between 1 and 12),
  status text not null check (status in ('processing','completed','failed','cancelled')),
  total_rows integer not null default 0,
  success_rows integer not null default 0,
  error_rows integer not null default 0,
  duplicate_rows integer not null default 0,
  imported_at timestamptz not null default now()
);
create index if not exists schedule_imports_recent_idx on public.schedule_imports(imported_at desc);

create table if not exists public.schedule_import_sessions (
  admin_id bigint primary key,
  year integer not null check (year between 2000 and 2100),
  month integer not null check (month between 1 and 12),
  import_type text not null check (import_type in ('weekly','monthly')),
  created_at timestamptz not null default now()
);
create table if not exists public.schedule_import_staging (
  id bigint generated by default as identity primary key,
  admin_id bigint not null,
  year integer not null check (year between 2000 and 2100),
  month integer not null check (month between 1 and 12),
  import_type text not null check (import_type in ('weekly','monthly')),
  file_name text not null,
  rows jsonb not null,
  errors jsonb not null default '[]'::jsonb,
  duplicate_count integer not null default 0,
  total_rows integer not null default 0,
  status text not null default 'pending' check (status in ('pending','processing','confirmed','cancelled')),
  created_at timestamptz not null default now()
);
create index if not exists schedule_import_staging_admin_idx on public.schedule_import_staging(admin_id,created_at desc);

-- The bot uses a server-side PostgreSQL connection as the trusted application.
-- No direct Data API access is granted to browser roles; RLS is defense in depth.
alter table public.users enable row level security;
alter table public.schedule_periods enable row level security;
alter table public.schedules enable row level security;
alter table public.schedule_imports enable row level security;
alter table public.schedule_import_sessions enable row level security;
alter table public.schedule_import_staging enable row level security;
revoke all on public.users, public.schedule_periods, public.schedules, public.schedule_imports from anon, authenticated;
revoke all on public.schedule_import_sessions, public.schedule_import_staging from anon, authenticated;
grant all on public.users, public.schedule_periods, public.schedules, public.schedule_imports, public.schedule_import_sessions, public.schedule_import_staging to service_role;
grant usage, select on all sequences in schema public to service_role;

comment on table public.schedule_periods is 'Versioned schedule imports; only one active version per year/month.';
comment on column public.schedules.lesson_date is 'Exact date for dated lessons; NULL means recurring weekday lesson within the period month.';
